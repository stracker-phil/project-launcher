/** The project colours, as the file stores them; each has a `--project-<name>` token. */
export const PROJECT_COLORS = ["Blue", "Green", "Magenta", "Orange", "Purple", "Red", "Yellow"];

/** An unknown name draws the folder. */
export function iconFor(name: string): LucideIcon {
  return ICONS[name] ?? Folder;
}

/** The token of a colour name; an unknown name is blue. */
export function colorVar(name: string): string {
  const known = PROJECT_COLORS.find((c) => c.toLowerCase() === name.toLowerCase()) ?? "Blue";
  return `var(--project-${known.toLowerCase()})`;
}

/** A project's icon on a tile of its colour. */
export function ProjectIcon({ icon, color, size = 32 }: { icon: string; color: string; size?: number }) {
  const Icon = iconFor(icon);
  return (
    <span className="project-tile" style={{ "--tile-color": colorVar(color), width: size, height: size } as CSSProperties}>
      <Icon size={Math.round(size * 0.55)} strokeWidth={1.8} aria-hidden />
    </span>
  );
}
